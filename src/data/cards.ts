/**
 * Assign each card a fixed spadeCategory — which of the 6 entries
 * gets the ♠ symbol. Uses a scrambled mapping so it's not simply
 * sequential but is deterministic per card.
 */
function pickSpadeCategory(index: number): BaseCategory {
  // Scramble using a simple multiplicative hash to avoid obvious patterns
  const scrambled = ((index * 7) + 3) % 6;
  return BASE_CATEGORIES[scrambled];
}

export const allCards: Card[] = raw.map((r, i) => ({
  id: `c${String(i).padStart(3, '0')}`,
  action: r[0],
  object: r[1],
  nature: r[2],
  random: r[3],
  person: r[4],
  world: r[5],
  difficulty: r[6],
  isSpade: r[7],
  spadeCategory: pickSpadeCategory(i),
}));

export const cardMap = new Map<string, Card>(allCards.map((c) => [c.id, c]));

export function validateDeck(): { duplicateWords: string[]; malformedCards: string[] } {
  const seen = new Map<string, string>(); // normalized -> original
  const duplicateWords: string[] = [];
  const malformedCards: string[] = [];

  for (const card of allCards) {
    const words = getCardWords(card);
    for (const w of words) {
      if (!w || w.trim().length === 0) {
        malformedCards.push(card.id);
        continue;
      }
      const norm = normalizeWord(w);
      if (seen.has(norm)) {
        duplicateWords.push(`"${w}" (card ${card.id}) duplicates "${seen.get(norm)}"`);
      } else {
        seen.set(norm, `${w} (card ${card.id})`);
      }
    }
  }

  return { duplicateWords, malformedCards };
}
